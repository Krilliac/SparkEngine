/**
 * @brief A single GPU-driven particle emitter
 *
 * Owns all GPU buffers (particle pool, alive/dead lists, indirect args)
 * and dispatches compute shaders for emission, simulation, sorting, and
 * billboard generation. Does NOT own the compute shader objects -- those
 * are shared across all emitters and owned by GPUParticleSystem.
 */
class GPUParticleEmitter
{
public:
    GPUParticleEmitter(const std::string& name, const GPUEmitterSettings& settings);
    ~GPUParticleEmitter();

    // Non-copyable, moveable
    GPUParticleEmitter(const GPUParticleEmitter&) = delete;
    GPUParticleEmitter& operator=(const GPUParticleEmitter&) = delete;
    GPUParticleEmitter(GPUParticleEmitter&&) noexcept = default;
    GPUParticleEmitter& operator=(GPUParticleEmitter&&) noexcept = default;

    /**
     * @brief Initialize all GPU buffers for this emitter
     * @param device D3D11 device
     * @param maxParticles Maximum particle pool capacity
     * @return S_OK on success
     */
    HRESULT Initialize(ID3D11Device* device, uint32_t maxParticles);

    /**
     * @brief Release all GPU resources
     */
    void Shutdown();

    // ---- Compute dispatch (called by GPUParticleSystem) ----

    /**
     * @brief Emit new particles via the emit compute shader
     * @param context Device context
     * @param emitShader Compiled emit compute shader
     * @param deltaTime Frame delta time
     * @param totalTime Accumulated time
     */
    void DispatchEmit(
        ID3D11DeviceContext* context,
        ID3D11ComputeShader* emitShader,
        float deltaTime,
        float totalTime);

    /**
     * @brief Simulate alive particles (physics, forces, death)
     * @param context Device context
     * @param simulateShader Compiled simulate compute shader
     * @param deltaTime Frame delta time
     * @param totalTime Accumulated time
     * @param view Current view matrix (for depth collision)
     * @param projection Current projection matrix
     * @param depthSRV Depth buffer SRV (can be nullptr if no collision)
     * @param screenWidth Viewport width
     * @param screenHeight Viewport height
     */
    void DispatchSimulate(
        ID3D11DeviceContext* context,
        ID3D11ComputeShader* simulateShader,
        float deltaTime,
        float totalTime,
        const XMMATRIX& view,
        const XMMATRIX& projection,
        ID3D11ShaderResourceView* depthSRV,
        uint32_t screenWidth,
        uint32_t screenHeight);

    /**
     * @brief Sort alive particles via GPU bitonic sort
     * @param context Device context
     * @param bitonicSortShader Bitonic sort compute shader
     * @param transposeShader Matrix transpose compute shader
     */
    void DispatchSort(
        ID3D11DeviceContext* context,
        ID3D11ComputeShader* bitonicSortShader,
        ID3D11ComputeShader* transposeShader);

    /**
     * @brief Generate billboard vertices from alive particles
     * @param context Device context
     * @param billboardShader Billboard generation compute shader
     * @param view Current view matrix
     * @param projection Current projection matrix
     * @param cameraPos Camera world position
     */
    void DispatchBillboardGeneration(
        ID3D11DeviceContext* context,
        ID3D11ComputeShader* billboardShader,
        const XMMATRIX& view,
        const XMMATRIX& projection,
        const XMFLOAT3& cameraPos);

    /**
     * @brief Issue an indirect draw call for the generated billboards
     * @param context Device context
     */
    void RenderIndirect(ID3D11DeviceContext* context) const;

    // ---- Playback control ----

    void Play();
    void Stop();
    void Pause();
    void Reset(ID3D11DeviceContext* context);
    void Burst(uint32_t count = 0); ///< 0 = use settings.burstCount

    // ---- Accessors ----

    void SetPosition(const XMFLOAT3& pos) { m_position = pos; }
    void SetRotation(const XMFLOAT3& rot) { m_rotation = rot; }
    const XMFLOAT3& GetPosition() const { return m_position; }
    const XMFLOAT3& GetRotation() const { return m_rotation; }
    const std::string& GetName() const { return m_name; }
    const GPUEmitterSettings& GetSettings() const { return m_settings; }
    GPUEmitterSettings& GetSettings() { return m_settings; }
    bool IsPlaying() const { return m_playing; }
    uint32_t GetMaxParticles() const { return m_maxParticles; }

    /**
     * @brief Read back the alive count from the GPU (stalls pipeline)
     * @param context Device context
     * @return Number of alive particles
     */
    uint32_t ReadAliveCount(ID3D11DeviceContext* context) const;

    // ---- Buffer accessors (for external binding) ----

    ID3D11ShaderResourceView* GetParticleSRV() const { return m_particleSRV.Get(); }
    ID3D11UnorderedAccessView* GetParticleUAV() const { return m_particleUAV.Get(); }
    ID3D11ShaderResourceView* GetBillboardSRV() const { return m_billboardSRV.Get(); }
    ID3D11Buffer* GetBillboardVertexBuffer() const { return m_billboardVertexBuffer.Get(); }
    ID3D11Buffer* GetIndirectDrawBuffer() const { return m_indirectDrawBuffer.Get(); }

private:
    // ---- Helper methods ----

    HRESULT CreateParticleBuffer(ID3D11Device* device);
    HRESULT CreateAliveDeadLists(ID3D11Device* device);
    HRESULT CreateIndirectBuffers(ID3D11Device* device);
    HRESULT CreateBillboardBuffer(ID3D11Device* device);
    HRESULT CreateSortBuffers(ID3D11Device* device);
    HRESULT CreateConstantBuffers(ID3D11Device* device);
    HRESULT CreateCounterStagingBuffer(ID3D11Device* device);

    void UpdateEmitConstantBuffer(ID3D11DeviceContext* context, uint32_t emitCount, float deltaTime, float totalTime);
    void UpdateSimulateConstantBuffer(
        ID3D11DeviceContext* context,
        float deltaTime,
        float totalTime,
        const XMMATRIX& view,
        const XMMATRIX& projection,
        uint32_t screenWidth,
        uint32_t screenHeight);
    void UpdateRenderConstantBuffer(
        ID3D11DeviceContext* context,
        const XMMATRIX& view,
        const XMMATRIX& projection,
        const XMFLOAT3& cameraPos);

    void SwapAliveListBuffers();

    // ---- Emitter identity ----

    std::string m_name;
    GPUEmitterSettings m_settings;

    // ---- Transform ----

    XMFLOAT3 m_position = {0, 0, 0};
    XMFLOAT3 m_rotation = {0, 0, 0};

    // ---- Playback state ----

    bool m_playing                = false;
    bool m_initialized            = false;
    float m_emissionAccumulator   = 0.0f;
    float m_elapsedTime           = 0.0f;
    float m_burstTimer            = 0.0f;
    uint32_t m_pendingBurst       = 0;
    uint32_t m_maxParticles       = 0;

    // ---- Particle pool (StructuredBuffer with UAV) ----

    ComPtr<ID3D11Buffer>              m_particleBuffer;
    ComPtr<ID3D11ShaderResourceView>  m_particleSRV;
    ComPtr<ID3D11UnorderedAccessView> m_particleUAV;

    // ---- Alive / Dead lists (Append/Consume structured buffers) ----

    ComPtr<ID3D11Buffer>              m_deadListBuffer;
    ComPtr<ID3D11UnorderedAccessView> m_deadListUAV;   ///< AppendStructuredBuffer

    ComPtr<ID3D11Buffer>              m_aliveListBuffer;
    ComPtr<ID3D11UnorderedAccessView> m_aliveListUAV;  ///< AppendStructuredBuffer
    ComPtr<ID3D11ShaderResourceView>  m_aliveListSRV;

    ComPtr<ID3D11Buffer>              m_aliveListBuffer2;   ///< Double-buffered alive list
    ComPtr<ID3D11UnorderedAccessView> m_aliveListUAV2;
    ComPtr<ID3D11ShaderResourceView>  m_aliveListSRV2;

    uint32_t m_currentAliveList   = 0; ///< 0 or 1, indexes the double-buffered alive list

    // ---- Indirect dispatch / draw argument buffers ----

    ComPtr<ID3D11Buffer> m_indirectDispatchBuffer;  ///< For DispatchIndirect
    ComPtr<ID3D11Buffer> m_indirectDrawBuffer;      ///< For DrawInstancedIndirect
    ComPtr<ID3D11UnorderedAccessView> m_indirectDispatchUAV;
    ComPtr<ID3D11UnorderedAccessView> m_indirectDrawUAV;

    // ---- Billboard vertex buffer ----

    ComPtr<ID3D11Buffer>              m_billboardVertexBuffer;
    ComPtr<ID3D11ShaderResourceView>  m_billboardSRV;
    ComPtr<ID3D11UnorderedAccessView> m_billboardUAV;

    // ---- Sort buffers ----

    ComPtr<ID3D11Buffer>              m_sortBuffer;
    ComPtr<ID3D11ShaderResourceView>  m_sortSRV;
    ComPtr<ID3D11UnorderedAccessView> m_sortUAV;

    ComPtr<ID3D11Buffer>              m_sortTempBuffer;
    ComPtr<ID3D11ShaderResourceView>  m_sortTempSRV;
    ComPtr<ID3D11UnorderedAccessView> m_sortTempUAV;

    // ---- Constant buffers ----

    ComPtr<ID3D11Buffer> m_emitCB;
    ComPtr<ID3D11Buffer> m_simulateCB;
    ComPtr<ID3D11Buffer> m_sortCB;
    ComPtr<ID3D11Buffer> m_renderCB;

    // ---- Staging buffer for GPU readback ----

    ComPtr<ID3D11Buffer> m_counterStagingBuffer;
};

