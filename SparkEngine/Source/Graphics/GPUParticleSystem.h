/**
 * @file GPUParticleSystem.h
 * @brief Compute-shader driven GPU particle system for high-volume effects
 * @author Spark Engine Team
 * @date 2026
 *
 * Provides a fully GPU-driven particle pipeline using D3D11 compute shaders.
 * Particles are emitted, simulated, sorted, and rendered entirely on the GPU
 * via structured buffers, append/consume buffers, indirect dispatch/draw,
 * and bitonic merge sort. Supports depth-buffer collision, multiple force
 * fields, and integrates with the existing ParticleSystem API.
 */

