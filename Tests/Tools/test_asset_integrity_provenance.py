#!/usr/bin/env python3
"""RDY-020: every asset-integrity entry carries license and provenance metadata.

The root manifest (schema v2) records, per file, a license identifier and a
provenance statement resolved deterministically from the reviewed policy in
tools/asset-integrity/provenance.json. These tests prove that resolution fails
closed: an unclaimed, ambiguously claimed, stale, or tampered provenance claim
is an error, never a silent default.
"""
